func DefaultHandlers() []Handler {
	out := make([]Handler, 0, len(MasterEffects))
	for i := range MasterEffects {
		if MasterEffects[i].Resolve == nil || MasterEffects[i].Hook == HookNone {
			continue
		}
		out = append(out, masterHandler{decl: &MasterEffects[i]})
	}
	return out
}

type masterHandler struct{ decl *EffectDecl }

func (h masterHandler) Matches(hook Hook, cardID model.CardID, _ string) bool {
	return h.decl != nil && h.decl.Resolve != nil && hook == h.decl.Hook && cardID == h.decl.CardID
}

func (h masterHandler) OnTrigger(ctx Context) error {
	if h.decl == nil || h.decl.Resolve == nil {
		return nil
	}
	return h.decl.Resolve(ctx)
}
